static void test_normal_checksum_real_rootblock(void) {
    CHECK(afs_block_valid(kTestffsRootblock, sizeof kTestffsRootblock, 20),
          "the REAL testffs.adf rootblock validates with its own stored checksum");
    CHECK_EQ_U(afs_block_checksum(kTestffsRootblock, 512, 20),
               be32(kTestffsRootblock + 20),
               "recomputing the checksum reproduces the stored value");

    uint8_t tmp[512];
    memcpy(tmp, kTestffsRootblock, 512);
    tmp[400] ^= 0xFF;
    CHECK(!afs_block_valid(tmp, 512, 20), "real block with a flipped byte is rejected");
}
